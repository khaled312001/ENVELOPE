/**
 * العربية — `/parking`, كيف يُصنع رقم المواقف.
 *
 * Held to `ParkingDictionary` by the type system, so this file cannot be missing a
 * key and cannot grow one the English does not have. Every term is checked against
 * `docs/05-design/arabic-glossary.md`; the comments here record only what would
 * otherwise read as a mistranslation.
 *
 * ---------------------------------------------------------------------------
 * THE PAGE THE CLIENT IS BUYING, SO THE TRADE TERMS AND NOT THE DICTIONARY ONES.
 *
 * موقف (ج. مواقف) for a bay, never «مكان وقوف»; ممرّ المناورة for the aisle between
 * bay rows and ممرّ المركبات for the driveway the dimension table names; المنحدر;
 * المصطبة for the podium; الارتدادات; مدخل المركبات; مسافة الابتعاد عن التقاطع for
 * the junction clearance; المسقط for a plan and المقطع for a section. A consultant
 * who lays out parking for a living meets one dictionary word where the trade word
 * belongs and stops reading.
 *
 * THREE CHOICES THAT WOULD OTHERWISE LOOK WRONG.
 *
 * 1. «سعة المواقف», NOT «العرض», FOR SUPPLY. «العرض» is the economist's supply, and
 *    on this page it is also «العَرض» — width — which the dimension table, the pack
 *    rectangle, the ramp strip and the access opening all use. «رقم العرض» would
 *    read as "the width figure" beside a column of widths. سعة is what the engine's
 *    `parking.provided_bays` is — what the declared levels hold — and it is glossed
 *    `(supply)` once, where it first appears.
 *
 * 2. «يملؤها تمامًا», NOT «مطابق», FOR "EXACT". The inscribed rectangle is exact when
 *    it coincides with the podium, and the natural Arabic for that is «مطابق». That
 *    word is reserved: the glossary lets it appear only negated, because predicated
 *    of anything this engine emits it reads as "compliant". The coincidence is said
 *    with «ينطبق» and «يملؤها», which carry geometry and nothing else.
 *
 * 3. «مُفترَض», NEVER «افتراضي». The one «افتراضية» below is the English's "no
 *    default", and it is negated in the same breath: «بلا قيمة افتراضية».
 *
 * ---------------------------------------------------------------------------
 * WHAT STAYS ENGLISH. Every string the engine emitted — the basis strings, the band
 * formula, the access rationales and refusal reasons, the not-assessed residue, the
 * verdict, the band and class tokens — is rendered by the component, not by this
 * file. Where one sits inside an Arabic sentence here (the band token, the class
 * token) it is wrapped in `Verbatim`: `dir="ltr" lang="en"` so a screen reader
 * switches voice and the bidirectional algorithm cannot carry a full stop to the
 * wrong end of it. Units stay Latin and figures stay Western, per §3 of the glossary.
 *
 * NO HEDGE: not one «قد» and not one «ربما». NO «نحن»: the product speaks of itself
 * in the third person, as the English does.
 */

